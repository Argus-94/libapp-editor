import { AnalyzeReport } from "./analyze";
import { DiffItem } from "./binary";

export function reportToMarkdown(r: AnalyzeReport): string {
  const lines: string[] = [];
  lines.push(`# LibApp Analyze Report`);
  lines.push(`- **File:** ${r.fileName}`);
  lines.push(`- **Size:** ${(r.fileSize / 1024 / 1024).toFixed(2)} MB (${r.fileSize} bytes)`);
  lines.push(`- **Editor:** ${r.version}`);
  lines.push(`- **Date:** ${new Date(r.analyzedAt).toISOString()}`);
  lines.push("");
  lines.push(`## Risk: ${r.risk.level} (score ${r.risk.score})`);
  lines.push(r.risk.autoUnlockAdvice);
  lines.push("");
  for (const reason of r.risk.reasons) {
    lines.push(`- ${reason}`);
  }
  lines.push("");
  lines.push(`## ELF`);
  lines.push(`- ELF: ${r.elf.isElf ? "yes" : "no"}`);
  lines.push(`- Class: ${r.elf.class}-bit, endian ${r.elf.endian}`);
  lines.push(`- Machine: ${r.elf.machine}, type ${r.elf.type}`);
  if (r.elf.textRange) {
    lines.push(
      `- .text: 0x${r.elf.textRange.start.toString(16)} – 0x${r.elf.textRange.end.toString(16)}`
    );
  }
  if (r.elf.snapshotHash) lines.push(`- Snapshot hash: \`${r.elf.snapshotHash}\``);
  for (const seg of r.elf.loadSegments) {
    lines.push(
      `- LOAD ${seg.flags} off=0x${seg.offset.toString(16)} vaddr=0x${seg.vaddr.toString(16)} size=0x${seg.filesz.toString(16)}`
    );
  }
  lines.push("");
  lines.push(`## Bool patterns (ARM64)`);
  lines.push(`| Pattern | Count |`);
  lines.push(`|---------|-------|`);
  lines.push(`| movz x0,#0 | ${r.patterns.movzX0False} |`);
  lines.push(`| movz x0,#1 | ${r.patterns.movzX0True} |`);
  lines.push(`| movz w0,#0 | ${r.patterns.movzW0False} |`);
  lines.push(`| movz w0,#1 | ${r.patterns.movzW0True} |`);
  lines.push(`| imm_ret (safe sites) | ${r.patterns.immRet} |`);
  lines.push(`| near_ret ≤12 | ${r.patterns.nearRet12} |`);
  lines.push(`| near_ret ≤32 | ${r.patterns.nearRet32} |`);
  lines.push(`| ret total | ${r.patterns.retCount} |`);
  lines.push("");
  lines.push(`## PRO / getter strings`);
  if (r.getterNames.length === 0) {
    lines.push(`_(none of the watched getter names)_`);
  } else {
    for (const s of r.getterNames) {
      lines.push(`- \`${s.hexOffset}\` **${s.key}** — \`${s.context}\``);
    }
  }
  lines.push("");
  lines.push(`## All categorized strings`);
  const byCat: Record<string, typeof r.strings> = {};
  for (const s of r.strings) {
    (byCat[s.category] ||= []).push(s);
  }
  for (const [cat, list] of Object.entries(byCat)) {
    lines.push(`### ${cat} (${list.length})`);
    for (const s of list.slice(0, 40)) {
      lines.push(`- \`${s.hexOffset}\` ${s.key}`);
    }
  }
  lines.push("");
  lines.push(`## Notes`);
  for (const n of r.notes) lines.push(`- ${n}`);
  lines.push("");
  lines.push(`---`);
  lines.push(`Generated by LibApp Editor ${r.version}`);
  return lines.join("\n");
}

export function reportToJson(r: AnalyzeReport): string {
  return JSON.stringify(r, null, 2);
}

export function diffToMarkdown(
  fileA: string,
  fileB: string,
  diffs: DiffItem[],
  sizeA: number,
  sizeB: number
): string {
  const lines: string[] = [];
  lines.push(`# SO Diff`);
  lines.push(`- **A:** ${fileA} (${sizeA} bytes)`);
  lines.push(`- **B:** ${fileB} (${sizeB} bytes)`);
  lines.push(`- **Regions:** ${diffs.length}${diffs.length >= 300 ? " (capped)" : ""}`);
  lines.push("");
  lines.push(`| Offset | Len | Old | New |`);
  lines.push(`|--------|-----|-----|-----|`);
  for (const d of diffs.slice(0, 200)) {
    lines.push(`| \`${d.hexOffset}\` | ${d.length} | \`${d.oldHex}\` | \`${d.newHex}\` |`);
  }
  if (diffs.length > 200) lines.push(`\n_…and ${diffs.length - 200} more_`);
  return lines.join("\n");
}
